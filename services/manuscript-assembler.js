// =============================================================================
// services/manuscript-assembler.js
// -----------------------------------------------------------------------------
// 把 draft_sections + PRISMA flow + SoF + Tables/Figures appendix + References
// 拼成一份完整的 Markdown(跟 export.md 路由共用同一段逻辑)。
//
// 为什么单独抽出来:之前只有 GET /report/export.md 用,现在新加 GET /report/preview
// 也需要同一份组装结果 → 必须 DRY,不然两边发散就成 bug 源。
//
// 输入(全部从 routes 层传进来,本模块不直接读 DB):
//   {
//     project, prismaCounts, sections, included,
//     prismaMermaid, postProc, sofMd, trSections,
//   }
//
// 输出:{ md, citationMap }
//
//   md            = 完整 markdown 字符串(包含 References + PRISMA + Tables/Figures)
//   citationMap   = { rec_xxx: { short: "Smith (2024)", anchor: "ref-rec_xxx" } }
//                   preview 页用这个把 [rec_xxx] 占位换成可点击徽章
//
// =============================================================================

import { exportReferencesSection, buildInlineCitationMap } from './reference-export.js'

/**
 * @typedef {Object} AssemblyInput
 * @prop {object} project
 * @prop {object} prismaCounts
 * @prop {Array}  included          listIncludedRecords() 输出
 * @prop {string} prismaMermaid     PRISMA mermaid 源码(已 trim)
 * @prop {object} postProc          postProcessFigTblPlaceholders() 输出
 * @prop {string} sofMd             SoF 表 markdown(可空)
 * @prop {Object<string,string>} trSections   8 段 markdown(占位已替换):
 *                                  { title, abstract, introduction, methods,
 *                                    results, discussion, limitations, conclusion }
 * @prop {string} renderPrismaTextSummary  PRISMA flow 文字总结(可空)
 * @prop {Array}  prismaChecklist   prisma_checklist DB 行(可空)
 * @prop {Array}  searchStrategies  search_strategies DB 行(可空)
 * @prop {string} [citationStyle]   apa / ieee / chicago / mla / gbt7714(default apa)
 */

/**
 * 拼装完整 markdown + 引文 anchor map。
 * 路由层负责所有 IO(查 DB / post-process);本服务只做字符串拼接。
 */
export function assembleManuscript({
  project,
  prismaCounts,
  included = [],
  prismaMermaid = '',
  postProc = {},
  sofMd = '',
  trSections = {},
  prismaTextSummary = '',
  prismaChecklist = [],
  searchStrategies = [],
  citationStyle = 'apa',
} = {}) {
  const parts = []
  parts.push(`<!-- Generated by SLR Copilot — ${new Date().toISOString()} -->`)
  if (project) parts.push(`<!-- Project: ${project.title} (${project.id}) -->`)
  if ((postProc.unknownTables && postProc.unknownTables.length)
      || (postProc.unknownFigures && postProc.unknownFigures.length)) {
    parts.push(`<!-- Phase D postproc: unknown_tables=${JSON.stringify(postProc.unknownTables || [])}, unknown_figures=${JSON.stringify(postProc.unknownFigures || [])} -->`)
  }
  parts.push('')

  // Title
  if (trSections.title) parts.push(trSections.title)
  else if (project) parts.push(`# ${project.title}`)
  parts.push('')

  // Abstract
  if (trSections.abstract) { parts.push(trSections.abstract); parts.push('') }

  // Introduction
  if (trSections.introduction) { parts.push(trSections.introduction); parts.push('') }

  // Methods + PRISMA flow
  if (trSections.methods) { parts.push(trSections.methods); parts.push('') }
  if (prismaMermaid) {
    parts.push('### PRISMA Flow Diagram')
    parts.push('')
    parts.push('```mermaid')
    parts.push(prismaMermaid)
    parts.push('```')
    parts.push('')
    if (prismaTextSummary) { parts.push(prismaTextSummary); parts.push('') }
  }

  // Results
  if (trSections.results) { parts.push(trSections.results); parts.push('') }

  // SoF (outcome-level GRADE summary)
  if (sofMd && sofMd.trim()) { parts.push(sofMd); parts.push('') }

  // Discussion
  if (trSections.discussion) { parts.push(trSections.discussion); parts.push('') }

  // Limitations
  if (trSections.limitations) { parts.push(trSections.limitations); parts.push('') }

  // Conclusion
  if (trSections.conclusion) { parts.push(trSections.conclusion); parts.push('') }

  // 2026-05-26 Declarations(PRISMA 24-27 — registration / funding /
  //   competing interests / data availability)— 放在 Conclusion 后、
  //   tables/figures appendices 前。trSections.declarations 若未生成则跳过。
  if (trSections.declarations) { parts.push(trSections.declarations); parts.push('') }

  // Tables / Figures appendices(Phase D — 放 References 之前)
  if (postProc.tablesAppendix) { parts.push(postProc.tablesAppendix); parts.push('') }
  if (postProc.figuresAppendix) { parts.push(postProc.figuresAppendix); parts.push('') }

  // References — 始终由 reference-export 生成(每条带 ref-rec_xxx anchor)
  parts.push(exportReferencesSection(included, { style: citationStyle }))
  parts.push('')

  // Appendix A: PRISMA 27 项 checklist
  if (Array.isArray(prismaChecklist) && prismaChecklist.length > 0) {
    parts.push('---')
    parts.push('')
    parts.push('## Appendix A. PRISMA 2020 Checklist')
    parts.push('')
    parts.push('| # | Section | Item | Status | Notes |')
    parts.push('|---|---|---|---|---|')
    const statusIcon = { done: '✓', in_progress: '◐', not_applicable: 'N/A', not_started: '○' }
    for (const it of prismaChecklist) {
      const status = statusIcon[it.status] || '○'
      const notes = (it.notes || '').replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 200)
      parts.push(`| ${it.item_number} | ${it.section || ''} | ${it.topic || ''} | ${status} | ${notes} |`)
    }
    parts.push('')
  }

  // Appendix B: search strategies
  if (Array.isArray(searchStrategies) && searchStrategies.length > 0) {
    parts.push('---')
    parts.push('')
    parts.push('## Appendix B. Search Strategies (verbatim)')
    parts.push('')
    for (const s of searchStrategies) {
      parts.push(`### ${s.database_name} · ${s.query_type}${s.search_date ? ' · ' + s.search_date : ''}${s.result_count != null ? ` · ${s.result_count} records` : ''}`)
      parts.push('')
      parts.push('```')
      parts.push(s.query_text || '')
      parts.push('```')
      parts.push('')
    }
  }

  const md = parts.join('\n')
  const citationMap = buildInlineCitationMap(included)
  return { md, citationMap }
}
